import { writeFileSync } from 'node:fs';
import { previewSamples } from './preview-samples.ts';

// Human descriptions for known merge keys (shared — a key means the same thing in every email).
// A key with no entry shows "—"; add it here when you introduce a new key.
const keyDescriptions: Record<string, string> = {
  company_name: 'Recipient company (greeting)',
  buyer_name: 'Recipient buyer name (greeting)',
  create_store_url: 'Primary CTA button link — use a tracked / per-send URL',
  become_supplier_url: 'Secondary CTA button link — tracked / per-send',
  explore_equipment_url: 'Buyer button link, "Explore equipment" (browse listings) — tracked / per-send',
  register_url: 'Buyer button link, "Register free" (create account) — tracked / per-send',
  sender_name: 'Sales rep name',
  sender_title: 'Sales rep job title',
  sender_phone: 'Phone as displayed, e.g. (+84)967.442.348',
  sender_whatsapp: 'Phone in clean international format for wa.me, e.g. 84967442348 (no +, spaces, dots)',
  sender_email: 'Sales rep email',
  sender_avatar: 'Full HTTPS URL of the rep photo (any ratio — object-fit crops it to a circle)',
  unsubscribe: 'Footer unsubscribe link',
};

export interface KeysDocEmail {
  name: string;
  category: string;
  subject: string;
  requiredKeys: string[];
}

/** Emit dist/KEYS.md — the per-email merge-key reference, generated from meta.requiredKeys. */
export function writeKeysDoc(outDir: string, emails: KeysDocEmail[], builtAt: string): void {
  const sections = emails
    .map((email) => {
      const rows = email.requiredKeys
        .map((key) => {
          const description = keyDescriptions[key] ?? '—';
          const sample = previewSamples[key] ? `\`${previewSamples[key]}\`` : '—';
          return `| \`{{${key}}}\` | ${description} | ${sample} |`;
        })
        .join('\n');
      return (
        `## ${email.name} — ${email.category} (${email.requiredKeys.length} keys)\n` +
        `**Subject:** ${email.subject}\n\n` +
        `| Key | Description | Sample (preview) |\n|---|---|---|\n${rows}\n`
      );
    })
    .join('\n');

  writeFileSync(
    `${outDir}/KEYS.md`,
    `# Merge keys — COMACPRO email templates\n\n` +
      `Auto-generated by the build (${builtAt}) from each email's \`meta.requiredKeys\`. **Do not edit by hand.**\n` +
      `These \`{{keys}}\` stay raw in \`<name>.html\` for the sending system to fill.\n\n` +
      sections,
  );
}
